from dataclasses import dataclass
from typing import Any, Protocol


@dataclass(frozen=True)
class FileResult:
    content: str | bytes
    media_type: str
    headers: dict[str, str]


class QueryResult(Protocol):
    data: Any


class ReadQuery(Protocol):
    def select(self, columns: str, **options: Any) -> "ReadQuery": ...
    def eq(self, field: str, value: Any) -> "ReadQuery": ...
    def neq(self, field: str, value: Any) -> "ReadQuery": ...
    def in_(self, field: str, values: list[Any]) -> "ReadQuery": ...
    def gt(self, field: str, value: Any) -> "ReadQuery": ...
    def gte(self, field: str, value: Any) -> "ReadQuery": ...
    def lt(self, field: str, value: Any) -> "ReadQuery": ...
    def lte(self, field: str, value: Any) -> "ReadQuery": ...
    def is_(self, field: str, value: Any) -> "ReadQuery": ...
    def ilike(self, field: str, pattern: str) -> "ReadQuery": ...
    def or_(self, filters: str) -> "ReadQuery": ...
    def contains(self, field: str, value: Any) -> "ReadQuery": ...
    def insert(self, values: Any, **options: Any) -> "ReadQuery": ...
    def update(self, values: dict, **options: Any) -> "ReadQuery": ...
    def delete(self, **options: Any) -> "ReadQuery": ...
    def upsert(self, values: Any, **options: Any) -> "ReadQuery": ...
    def order(self, field: str, **options: Any) -> "ReadQuery": ...
    def range(self, start: int, end: int) -> "ReadQuery": ...
    def limit(self, count: int) -> "ReadQuery": ...
    def execute(self) -> QueryResult: ...


class DataGateway(Protocol):
    def table(self, resource: str) -> ReadQuery: ...
    def rpc(self, operation: str, arguments: dict) -> ReadQuery: ...


class InvitationSender(Protocol):
    def configured(self) -> bool: ...
    def send(self, invitation: dict, code: str, token_hash: str) -> str: ...


class IntegrationDelivery(Protocol):
    def configuration(self, destination: str) -> Any: ...
    def configured_destinations(self) -> dict[str, bool]: ...
