"""Generate the reviewable demo-only SQL seed. Does not connect to a database."""

import json
from pathlib import Path
from uuid import UUID

ROOT = Path(__file__).resolve().parents[1]


def sql_string(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_sql() -> str:
    data = json.loads((ROOT / "knowledge_base/demo/articles.json").read_text(encoding="utf-8"))
    rows = []
    seen = set()
    for article in data["articles"]:
        article_id = str(UUID(article["id"]))
        if article_id in seen or not article["source_title"].startswith("Демо:"):
            raise ValueError("Expected unique IDs and explicitly labeled demo sources")
        seen.add(article_id)
        keywords = "array[" + ", ".join(sql_string(word) for word in article["keywords"]) + "]::text[]"
        rows.append("(" + ", ".join([
            sql_string(article_id), sql_string(article["title"]),
            sql_string(article["content"]), sql_string(article["source_title"]),
            "null" if article["source_url"] is None else sql_string(article["source_url"]),
            keywords, "true" if article["active"] else "false",
            sql_string(article["version"]), sql_string(article["editorial_state"]),
        ]) + ")")
    return (
        "-- Generated by scripts/export_jana_demo.py from knowledge_base/demo/articles.json.\n"
        "-- DEMO DATA ONLY, not approved Jana Post HR policy.\n"
        "-- LOCAL TEST / EXPLICIT LOCAL CONTAINER DATABASE ONLY: apply after database/migration-plan.json.\n"
        "-- Reuses the first three demo IDs; other articles are not deleted.\n"
        "begin;\nset local standard_conforming_strings = on;\n"
        "do $$ begin if left(current_database(),14) <> 'posttech_test_' and not "
        "(current_database()='posttech_local' and coalesce(current_setting('posttech.local_container',true),'')='on') "
        "then raise exception 'Local test database or explicit local container required'; end if; end $$;\n"
        "insert into public.knowledge_articles\n"
        "    (id, title, content, source_title, source_url, keywords, active, version, editorial_state)\nvalues\n"
        + ",\n".join(rows)
        + "\non conflict (id) do update set\n"
        "    title = excluded.title, content = excluded.content,\n"
        "    source_title = excluded.source_title, source_url = excluded.source_url,\n"
        "    keywords = excluded.keywords, active = excluded.active,\n"
        "    version = excluded.version, editorial_state = excluded.editorial_state\n"
        "    where knowledge_articles.source_title like 'Демо:%';\n"
        # Content edits invalidate review dates by trigger; set them in separate statements.
        + "\n".join("update public.knowledge_articles set reviewed_at = "
                       + sql_string(a["reviewed_at"]) + ", review_due_at = " + sql_string(a["review_due_at"])
                       + " where id = " + sql_string(a["id"]) + " and source_title like 'Демо:%';"
                       for a in data["articles"])
        + "\ncommit;\n"
    )


if __name__ == "__main__":
    target = ROOT / "database/seed_jana_demo.sql"
    target.write_text(render_sql(), encoding="utf-8", newline="\n")
    print(f"Written: {target}")
