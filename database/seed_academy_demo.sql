## 2. Пароли не нужны для помощи

Пароль, код подтверждения и токен доступа нельзя отправлять коллеге, в комментарий заявки или в AI Jana. Сообщение «пришлите пароль для ускорения согласования» не является частью нормального процесса. Закройте подозрительный запрос и сообщите ответственному администратору. После работы на общем устройстве завершите сеанс.

## 3. Проверяйте источник ответа

AI Jana ищет информацию в подготовленной базе знаний и показывает источник. Наличие ответа не означает, что помощник принимает кадровое решение. Если информации недостаточно, корректный результат — прямое сообщение об отсутствии надёжного ответа и обращение в HR.

Прежде чем использовать найденное правило, откройте указанный источник и убедитесь, что он относится к вашему вопросу. Не подставляйте реальные персональные данные в вопрос помощнику. Лучше спросить «Как подать заявку на отпуск?», чем перечислять чужие даты, номера документов или медицинские обстоятельства.

